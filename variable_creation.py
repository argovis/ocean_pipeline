import numpy, argparse, glob, pandas, gsw, os
from helpers import helpers

# argument setup
def str_list(value):
    return value.split(',')

def float_list(value):
    return [float(x) for x in value.split(',')]

def nullable_string(value):
    if value == 'None':
        return None
    else:
        return str(value)

def nullable_float(value):
    if value == 'None':
        return None
    else:
        return float(value)

parser = argparse.ArgumentParser()
parser.add_argument("--input_file", type=str, help="parquet file generated by upstream adaptor like argovis_input.py")
parser.add_argument("--output_file", type=str, help="name of output file, with path.")
parser.add_argument("--variables", type=str_list, help="variable to compute. One of 'absolute_salinity', 'potential_temperature', 'conservative_temperature', 'potential_density', 'mld', 'dynamic_height_anom', 'steric_hgt_anom', 'thermosteric_hgt_anom_linear', 'halosteric_hgt_anom_linear', 'thermosteric_hgt_anom', 'halosteric_hgt_anom'")
parser.add_argument("--integration_mode", type=nullable_string, help="integration method to use. One of 'trapezoidal' (requires --pressure_range), or 'dz'. No integration is performed if this option is omitted.")
parser.add_argument("--pressure_range", type=float_list, help="min,max pressure range, CSV.")
parser.add_argument("--interpolate_level", type=nullable_float, help="level to interpolate to; only used in conjunction with variables with meaningful per-level values.")

args = parser.parse_args()

# could consider some if this then that enforcement for argument defs; for now just let it blow up when used incorrectly

df = pandas.read_parquet(args.input_file, engine='pyarrow')
rejects = pandas.DataFrame(columns=['float', 'cycle', 'longitude', 'latitude', 'juld', 'flag'])

# --variables we consider fall into two categories: 
# per-level basic values (mostly thermodynamics, GSW transforms, and dataframe columns passed in as is),
# and derived variables.
# basic values might be interpolated to a specific level or integrated per flags;
# derived variables specify their own interpolation and integration behavior in their respective functions which may or may not consume the flag. 
basic_values = ['absolute_salinity', 'potential_temperature', 'conservative_temperature', 'potential_density']
derived_values = ['mld', 'dynamic_height_anom', 'steric_hgt_anom', 'thermosteric_hgt_anom_linear', 'halosteric_hgt_anom_linear', 'thermosteric_hgt_anom', 'halosteric_hgt_anom']

if len(df) > 0:

    # first make sure all necessary basic GSW columns exist
    for var in args.variables:
        ## absolute salinity
        if var in ['absolute_salinity', 'potential_temperature', 'conservative_temperature', 'potential_density', 'mld', 'dynamic_height_anom', 'steric_hgt_anom', 'thermosteric_hgt_anom_linear', 'halosteric_hgt_anom_linear', 'thermosteric_hgt_anom', 'halosteric_hgt_anom'] and 'absolute_salinity' not in df.columns:
            df['absolute_salinity'] = df.apply(
                lambda row: gsw.conversions.SA_from_SP(
                    row['salinity'], row['pressure'], row['longitude'], row['latitude']
                ),
                axis=1
            )

        ## potential temperature
        if var in ['potential_temperature'] and 'potential_temperature' not in df.columns:
            df['potential_temperature'] = df.apply(
                lambda row: gsw.conversions.pt0_from_t(
                    row['absolute_salinity'], row['temperature'], row['pressure']
                ),
                axis=1
            )

        ## conservative temperature
        if var in ['conservative_temperature', 'potential_density', 'mld', 'dynamic_height_anom', 'steric_hgt_anom', 'thermosteric_hgt_anom_linear', 'thermosteric_hgt_anom'] and 'conservative_temperature' not in df.columns:
            df['conservative_temperature'] = df.apply(
                lambda row: gsw.conversions.CT_from_t(
                    row['absolute_salinity'], row['temperature'], row['pressure']
                ),
                axis=1
            )
        
        ## potential density
        if var in ['potential_density', 'mld'] and 'potential_density' not in df.columns:
            df['potential_density'] = df.apply(
                lambda row: gsw.sigma0(
                    row['absolute_salinity'], row['conservative_temperature']
                ),
                axis=1
            )

    # next split out into derived values and basic values. 
    # Basic values have generic integration and interpolation schemes, 
    # while derived values may need more case-by-case flexibility. 
    dv = list(set(args.variables).intersection(set(derived_values)))
    bv = [x for x in args.variables if x not in dv]

    # handle derived values first in case they need to consume the unadulerated basic values.
    for var in dv:
        if var == 'mld' and 'mld' not in df.columns:
            df[['mld', 'flag']] = df.apply(
                lambda row: pandas.Series(helpers.mld_estimator(row)), 
	            axis=1
            )

        if var == 'dynamic_height_anom' and 'dynamic_height_anom' not in df.columns:
            df[['dynamic_height_anom', 'flag']] = df.apply(
                lambda row: pandas.Series(helpers.dha(row, args.pressure_range)),
                axis=1
            )

        if var in ['steric_hgt_anom', 'thermosteric_hgt_anom_linear', 'halosteric_hgt_anom_linear', 'thermosteric_hgt_anom', 'halosteric_hgt_anom'] and var not in df.columns:
            df[[var, 'flag']] = df.apply(
                lambda row: pandas.Series(helpers.ecco_steric_estimators(var, row, args.pressure_range, args.integration_mode)),
                axis=1
            )

    # now its safe to mutate the basics with integrals and interpolation as requested
    for var in bv:
        if args.integration_mode is not None:
            if args.integration_mode == 'trapezoidal':
                df[[var, 'flag']] = df.apply(
                    lambda row: pandas.Series(helpers.trapezoidal_integration(row, var, args.pressure_range)),
                    axis=1
                )
            elif args.integration_mode == 'dz':
                df[[var, 'flag']] = df.apply(
                    lambda row: pandas.Series(helpers.dz_integration(row, var)),
                    axis=1
                )
            else:
                raise ValueError("integration mode not recognized")
        elif args.interpolate_level is not None:
            df[[var, 'flag']] = df.apply(
                lambda row: pandas.Series(helpers.interpolate_to_levels(row, var, [args.interpolate_level])),
                axis=1
            )

    # if any profile has failed to support the calculation of every requested result, drop it.
    # failures are represented by a vector of None for the failed computation.
    dumpmask = df[args.variables].apply(
        lambda row: all(all((v is None or numpy.isnan(v)) for v in x) for x in row),
        axis=1
    )
    dumps = df[dumpmask].reset_index(drop=True)
    dumps = dumps[['float', 'cycle', 'longitude', 'latitude', 'juld', 'flag']]
    rejects = pandas.concat([rejects,dumps], ignore_index=True)
    df = df[~dumpmask].reset_index(drop=True)

rejects.to_parquet(os.path.join(args.output_file.split('.')[0] + '_rejects.parquet'), engine='pyarrow')
df.to_parquet(args.output_file, engine='pyarrow')
